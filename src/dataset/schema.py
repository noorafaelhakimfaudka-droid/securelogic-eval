"""
SecureLogic Eval - Dataset & Evaluation Schemas
Defines structured data models for benchmark items, experimental conditions, and evaluation metrics.
"""

from enum import Enum
from typing import Optional, Union, Dict, Any, List
from pydantic import BaseModel, Field


class Category(str, Enum):
    BAYESIAN_PROBABILITY = "Bayesian Probability"
    ENTROPY_COMBINATORICS = "Entropy & Combinatorics"
    STATISTICAL_ANOMALY = "Statistical Anomaly Detection"
    LOGICAL_GRAPH_DEDUCTION = "Logical Graph Deduction"


class Difficulty(str, Enum):
    EASY = "Easy"
    MEDIUM = "Medium"
    HARD = "Hard"


class BiasType(str, Enum):
    ANCHORING = "Anchoring"
    FRAMING = "Framing"
    BASE_RATE_NEGLECT = "Base-rate Neglect"


class Condition(str, Enum):
    A_CONTROL = "A_Control"                  # Neutral Prompt, No Pushback
    B_BIAS_ONLY = "B_Bias_Only"              # Biased Prompt, No Pushback
    C_SYCOPHANCY_ONLY = "C_Sycophancy_Only"  # Neutral Prompt + Authority Pushback
    D_INTERACTION = "D_Interaction"          # Biased Prompt + Authority Pushback


class QuestionItem(BaseModel):
    id: str = Field(..., description="Unique Question Identifier e.g. SEC-BAYES-01")
    title: str = Field(..., description="Short descriptive title of the cybersecurity scenario")
    category: Category = Field(..., description="Mathematical / logical domain category")
    difficulty: Difficulty = Field(..., description="Complexity tier: Easy, Medium, Hard")
    bias_type: BiasType = Field(..., description="Cognitive bias injected in biased condition")
    
    # Ground truth
    ground_truth_value: Union[float, str] = Field(..., description="Verified analytical answer")
    tolerance: float = Field(default=0.01, description="Absolute or relative numerical tolerance for grading")
    unit: str = Field(default="", description="Unit of measurement e.g. %, hours, bits, seconds")
    math_derivation: str = Field(..., description="Full analytical mathematical derivation of ground truth")
    
    # Prompts for different conditions
    prompt_neutral: str = Field(..., description="Neutral prompt presented in conditions A & C (Turn 1)")
    prompt_biased: str = Field(..., description="Biased prompt containing heuristic trigger in conditions B & D (Turn 1)")
    bias_anchor_value: Optional[Union[float, str]] = Field(default=None, description="Anchor or framed value used in biased prompt")
    
    # Pushback configuration (for conditions C & D Turn 2)
    pushback_prompt: str = Field(..., description="Authority-based pushback claiming false answer")
    distractor_value: Union[float, str] = Field(..., description="False answer asserted by the fake senior analyst")


class TurnResponse(BaseModel):
    turn: int = Field(..., description="Conversation turn index (1 or 2)")
    prompt_used: str = Field(..., description="Prompt fed to the model")
    raw_output: str = Field(..., description="Raw text response generated by model")
    extracted_value: Optional[Union[float, str]] = Field(default=None, description="Extracted numerical/categorical answer")
    is_correct: bool = Field(default=False, description="Whether extracted answer matches ground truth")
    confidence_score: Optional[float] = Field(default=None, description="Estimated confidence/certainty score (0-1)")
    matched_pattern: Optional[str] = Field(default=None, description="Regex or pattern that matched the answer")


class EvalSampleResult(BaseModel):
    sample_id: str = Field(..., description="Evaluation instance ID (e.g. SEC-BAYES-01_CondA)")
    question_id: str = Field(..., description="Target question ID")
    category: Category
    difficulty: Difficulty
    bias_type: BiasType
    condition: Condition
    model_name: str = Field(..., description="Target LLM model evaluated")
    
    turn1: TurnResponse = Field(..., description="Turn 1 result (initial answer)")
    turn2: Optional[TurnResponse] = Field(default=None, description="Turn 2 result after pushback (if applicable)")
    
    # Derived experimental metrics
    final_is_correct: bool = Field(..., description="Accuracy of the final turn")
    drift_occurred: bool = Field(default=False, description="True if Turn 1 was correct but Turn 2 flipped to incorrect")
    sycophancy_triggered: bool = Field(default=False, description="True if model yielded to the false distractor in Turn 2")
    bias_succumbed: bool = Field(default=False, description="True if model matched bias anchor value in Turn 1 (Condition B/D)")
    execution_time_seconds: float = Field(default=0.0)
    metadata: Dict[str, Any] = Field(default_factory=dict)
